export type I18nKey = keyof typeof DICT.en;

type I18nValue = {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: I18nKey) => string;
  topicLabel: (topic: string) => string;
};

const I18nContext = createContext<I18nValue>({
  lang: "en",
  setLang: () => {},
  t: (key) => DICT.en[key],
  topicLabel: (topic) => topic,
});

function readStoredLang(): Lang {
  if (typeof window === "undefined") return "en";
  try {
    const v = window.localStorage.getItem("velora_lang");
    if (v === "en" || v === "hi" || v === "hng") return v;
  } catch {
    /* ignore */
  }
  return "en";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readStoredLang);
  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    try {
      window.localStorage.setItem("velora_lang", next);
    } catch {
      /* ignore */
    }
  }, []);
  const t = useCallback(
    (key: I18nKey) => DICT[lang][key] || DICT.en[key] || key,
    [lang],
  );
  const topicLabel = useCallback(
    (topic: string) => {
      const key = `topic_${topic}`;
      const table = DICT[lang] as Record<string, string>;
      const en = DICT.en as Record<string, string>;
      return table[key] || en[key] || topic;
    },
    [lang],
  );
  const value = useMemo(() => ({ lang, setLang, t, topicLabel }), [lang, setLang, t, topicLabel]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}

