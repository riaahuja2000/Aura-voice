export type I18nKey = keyof typeof DICT.en;

type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: I18nKey) => string;
  topicLabel: (topic: string) => string;
};

const I18nContext = createContext<Ctx>({
  lang: "en",
  setLang: () => {},
  t: (k) => DICT.en[k],
  topicLabel: (t) => t,
});

const LANG_KEY = "velora_lang";

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    storage.getItem<string>(LANG_KEY, "en").then((v) => {
      if (v === "en" || v === "hi" || v === "hng") setLangState(v);
    });
  }, []);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    storage.setItem(LANG_KEY, next);
  }, []);

  const t = useCallback((key: I18nKey) => (DICT[lang] as any)[key] || (DICT.en as any)[key] || key, [lang]);
  const topicLabel = useCallback(
    (topic: string) => {
      const key = `topic_${topic}`;
      return (DICT[lang] as any)[key] || (DICT.en as any)[key] || topic;
    },
    [lang],
  );

  const value = useMemo(() => ({ lang, setLang, t, topicLabel }), [lang, setLang, t, topicLabel]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
